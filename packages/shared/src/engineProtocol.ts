import {
  CREATE_ORDER,
  CANCEL_ORDER,
  ON_RAMP,
  GET_DEPTH,
  GET_OPEN_ORDERS,
  ADD_USER,
  DEPTH,
  ORDER_PLACED,
  ORDER_CANCELLED,
  OPEN_ORDERS,
  NEW_USER,
} from "./engineEvents.js";

// ---------------------------------------------------------------------------
// Requests  API Gateway → Matcher Service
// ---------------------------------------------------------------------------

export type EngineRequest =
  | {
      type: typeof CREATE_ORDER;
      data: {
        symbol: string;          // e.g. "RIL_INR"
        price: string;           // limit price; "0" for market orders
        quantity: string;
        side: "buy" | "sell";
        userId: string;
        orderType: "limit" | "market";
        // Internal orderId generated by api-gateway and passed through so
        // the execution-service can persist it without generating a new one.
        orderId: string;
      };
    }
  | {
      type: typeof CANCEL_ORDER;
      data: {
        orderId: string;
        symbol: string;
      };
    }
  | {
      type: typeof ON_RAMP;
      data: {
        amount: string;
        userId: string;
        txnId: string;
      };
    }
  | {
      type: typeof GET_DEPTH;
      data: {
        symbol: string;
      };
    }
  | {
      type: typeof GET_OPEN_ORDERS;
      data: {
        userId: string;
        symbol: string;
      };
    }
  | {
      type: typeof ADD_USER;
      data: {
        userId: string;
        wallet: {
          userId: string;
          balance: any;
          assetsHeld: any;
        };
      };
    };

// ---------------------------------------------------------------------------
// Responses  Matcher Service → API Gateway
// ---------------------------------------------------------------------------

export type EngineResponse =
  | {
      type: typeof DEPTH;
      payload: {
        symbol: string;
        bids: [string, string][];
        asks: [string, string][];
      };
    }
  | {
      type: typeof ORDER_PLACED;
      payload: {
        orderId: string;
        executedQty: number;
        remainingQty: number;
        restingOnBook: boolean;
        fills: {
          price: string;
          qty: number;
          matchId: string;   // CortexCookie naming: matchId instead of tradeId
        }[];
      };
    }
  | {
      type: typeof ORDER_CANCELLED;
      payload: {
        orderId: string;
        executedQty: number;
        remainingQty: number;
        error?: string;
      };
    }
  | {
      type: typeof OPEN_ORDERS;
      payload: {
        orderId: string;
        executedQty: number;
        price: string;
        quantity: string;
        side: "buy" | "sell";
        userId: string;
      }[];
    }
  | {
      type: typeof ON_RAMP;
      payload: {
        status: "success" | "error";
        message: string;
        txnId?: string;
      };
    }
  | {
      type: typeof NEW_USER;
      payload: {
        status: "success" | "error";
      };
    };
